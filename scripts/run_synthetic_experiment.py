"""SYNTHETIC experiment: does headline sentiment predict next-day returns?

Runs the full pipeline (score headlines -> assign to sessions -> daily mean
-> align with forward 1-day return -> evaluate) on seeded synthetic data
from newsnlp.synthetic, for two scenarios:

* drift: returns have a small predictable component (b = 0.1)
* null:  nothing is predictable (b = 0)

Each scenario is evaluated three ways:

* oracle:   the latent factor z_t itself (upper bound for any signal)
* session:  headline sentiment with point-in-time session assignment
* calendar: headline sentiment bucketed by calendar date (look-ahead leak)

Writes results/synthetic_experiment.csv (one row per seed and method) and
results/synthetic_experiment.md (summary). No market data is used.
"""

from __future__ import annotations

import argparse
from dataclasses import asdict
from pathlib import Path

import pandas as pd

from newsnlp.align import align, assign_calendar_date, assign_session, daily_sentiment
from newsnlp.stats import evaluate
from newsnlp.synthetic import SyntheticConfig, generate
from newsnlp.text import score_articles

SCENARIOS = {"drift": dict(a=0.5, b=0.1), "null": dict(a=0.5, b=0.0)}


def run(n_seeds: int, n_days: int) -> pd.DataFrame:
    rows = []
    for name, params in SCENARIOS.items():
        for seed in range(n_seeds):
            cfg = SyntheticConfig(n_days=n_days, seed=seed, **params)
            d = generate(cfg)
            news = score_articles(d.news)
            signals = {"oracle": d.z}
            for method, assign in (
                ("session", lambda s: assign_session(s, d.close.index)),
                ("calendar", assign_calendar_date),
            ):
                tmp = news.assign(session=assign(news["published_at"]))
                signals[method] = daily_sentiment(tmp)["sentiment"]
            for method, sig in signals.items():
                rep = evaluate(align(sig, d.close, horizon=1))
                rows.append(
                    {"scenario": name, "a": cfg.a, "b": cfg.b, "seed": seed, "method": method,
                     "true_oracle_ic": d.true_forward_ic(), **asdict(rep)}
                )
    return pd.DataFrame(rows)


def summarise(df: pd.DataFrame) -> pd.DataFrame:
    g = df.groupby(["scenario", "method"], sort=False)
    out = pd.DataFrame({
        "theory_oracle_ic": g["true_oracle_ic"].first(),
        "mean_ic": g["pearson_ic"].mean(),
        "sd_ic": g["pearson_ic"].std(ddof=1),
        "mean_t": g["t_stat"].mean(),
        "mean_hit_rate": g["hit_rate"].mean(),
        "mean_sharpe": g["sharpe"].mean(),
        "n_days": g["n"].mean(),
    })
    return out.reset_index()


def to_markdown(summary: pd.DataFrame, n_seeds: int, n_days: int) -> str:
    cols = ["scenario", "method", "theory_oracle_ic", "mean_ic", "sd_ic",
            "mean_t", "mean_hit_rate", "mean_sharpe", "n_days"]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in summary[cols].iterrows():
        cells = [r["scenario"], r["method"]] + [f"{r[c]:.3f}" for c in cols[2:-1]] + [f"{r['n_days']:.0f}"]
        lines.append("| " + " | ".join(cells) + " |")
    table = "\n".join(lines)
    return f"""# SYNTHETIC experiment results

Data: SYNTHETIC, generated by `newsnlp.synthetic` (seeds 0..{n_seeds - 1},
{n_days} business days per seed, about 3 template headlines per day). No real
news or market data. Signal: daily mean TextBlob polarity. Target: next-day
close-to-close return. Rule for hit rate and Sharpe: sign(signal), no costs.

`theory_oracle_ic` is the closed-form correlation b / sqrt(a^2 + b^2 + 1)
between the latent factor and the forward return. Means and standard
deviations are across seeds.

{table}

Command: `python scripts/run_synthetic_experiment.py --seeds {n_seeds} --days {n_days}`
"""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--seeds", type=int, default=20)
    ap.add_argument("--days", type=int, default=1000)
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parent.parent / "results")
    args = ap.parse_args()

    df = run(args.seeds, args.days)
    summary = summarise(df)
    args.out.mkdir(parents=True, exist_ok=True)
    df.to_csv(args.out / "synthetic_experiment.csv", index=False, float_format="%.6f")
    md = to_markdown(summary, args.seeds, args.days)
    (args.out / "synthetic_experiment.md").write_text(md)
    print(md)


if __name__ == "__main__":
    main()
